/**
 * Returns the SEO profile for a given tool slug, falling back to clean generated defaults.
 */
export function getToolSeoProfile(slug: string): ToolSeoProfile | undefined {
  const clean = (slug || '').toLowerCase().trim();
  return TOOL_SEO_PROFILES[clean];
}

/**
 * Aggregates all effective keywords for a tool:
 * merges base SEO profile keywords with any admin overrides.
 */
export function getEffectiveToolKeywords(
  slug: string,
  baseKeywords: string[] = [],
  customKeywords?: string[]
): string[] {
  if (customKeywords && customKeywords.length > 0) {
    return Array.from(new Set(customKeywords.map(k => k.trim()).filter(Boolean)));
  }

  const profile = getToolSeoProfile(slug);
  const collected = new Set<string>();

  if (profile) {
    if (profile.primaryKeyword) collected.add(profile.primaryKeyword);
    profile.secondaryKeywords.forEach(k => collected.add(k));
    profile.longTailKeywords.forEach(k => collected.add(k));
  }

  baseKeywords.forEach(k => collected.add(k));

  return Array.from(collected);
}

