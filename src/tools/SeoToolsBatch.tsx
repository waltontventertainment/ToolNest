export const SeoContentReadabilityAudit: React.FC = () => {
  const [content, setContent] = useState(
    `Search Engine Optimization involves optimizing your website content to improve visibility in organic search engine results. Search engines evaluate readability, keyword context, user engagement, and bounce rates when determining page rankings.`
  );

  const readabilityStats = useMemo(() => {
    const sentences = content.split(/[.!?]+/).filter(Boolean);
    const words = content.split(/\s+/).filter(Boolean);

    const totalWords = words.length;
    const totalSentences = sentences.length || 1;

    // Simple syllable counter heuristic
    let totalSyllables = 0;
    words.forEach((w) => {
      const clean = w.toLowerCase().replace(/[^a-z]/g, '');
      totalSyllables += Math.max(1, clean.replace(/[^aeiouy]+/g, '').length);
    });

    // Flesch Reading Ease Formula
    const fleschEase =
      totalWords > 0
        ? Math.round(206.835 - 1.015 * (totalWords / totalSentences) - 84.6 * (totalSyllables / totalWords))
        : 100;

    let easeLabel = 'Easy to read';
    if (fleschEase < 50) easeLabel = 'Difficult / Academic';
    else if (fleschEase < 70) easeLabel = 'Standard / Plain English';

    return {
      totalWords,
      totalSentences,
      avgWordsPerSentence: (totalWords / totalSentences).toFixed(1),
      fleschEase,
      easeLabel,
    };
  }, [content]);

  return (
    <div className="space-y-6">
      <div className="space-y-2">
        <label className="block text-xs font-semibold text-foreground">Paste Web Article Copy</label>
        <textarea
          rows={6}
          value={content}
          onChange={(e) => setContent(e.target.value)}
          className="w-full p-3 text-xs border border-border rounded-xl"
        />
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        <div className="bg-card border border-border p-4 rounded-xl text-center shadow-xs">
          <span className="text-[10px] font-bold text-muted-foreground uppercase">Flesch Reading Ease</span>
          <p className="text-2xl font-black text-indigo-600">{readabilityStats.fleschEase}</p>
          <span className="text-xs text-muted-foreground font-medium">{readabilityStats.easeLabel}</span>
        </div>
        <div className="bg-card border border-border p-4 rounded-xl text-center shadow-xs">
          <span className="text-[10px] font-bold text-muted-foreground uppercase">Total Words</span>
          <p className="text-2xl font-black text-foreground">{readabilityStats.totalWords}</p>
        </div>
        <div className="bg-card border border-border p-4 rounded-xl text-center shadow-xs">
          <span className="text-[10px] font-bold text-muted-foreground uppercase">Avg Words / Sentence</span>
          <p className="text-2xl font-black text-foreground">{readabilityStats.avgWordsPerSentence}</p>
        </div>
      </div>
    </div>
  );
};
