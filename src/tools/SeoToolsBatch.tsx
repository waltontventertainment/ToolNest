// 1. Robots.txt Generator & Validator
// ============================================================================
export const RobotsTxtGenerator: React.FC = () => {
  const [sitemapUrl, setSitemapUrl] = useState('https://example.com/sitemap.xml');
  const [crawlDelay, setCrawlDelay] = useState('');
  const [rules, setRules] = useState([
    { userAgent: '*', type: 'disallow' as 'allow' | 'disallow', path: '/admin/' },
    { userAgent: '*', type: 'disallow' as 'allow' | 'disallow', path: '/private/' },
    { userAgent: 'Googlebot', type: 'allow' as 'allow' | 'disallow', path: '/' },
    { userAgent: 'GPTBot', type: 'disallow' as 'allow' | 'disallow', path: '/' },
  ]);
  const [copied, setCopied] = useState(false);
  const [testUrl, setTestUrl] = useState('/admin/login');
  const [testBot, setTestBot] = useState('*');

  const addRule = () => {
    setRules([...rules, { userAgent: '*', type: 'disallow', path: '' }]);
  };

  const removeRule = (index: number) => {
    setRules(rules.filter((_, i) => i !== index));
  };

  const updateRule = (index: number, field: string, value: string) => {
    const updated = [...rules];
    updated[index] = { ...updated[index], [field]: value };
    setRules(updated);
  };

  const applyPreset = (preset: 'wordpress' | 'ecommerce' | 'ai-block') => {
    if (preset === 'wordpress') {
      setRules([
        { userAgent: '*', type: 'disallow', path: '/wp-admin/' },
        { userAgent: '*', type: 'allow', path: '/wp-admin/admin-ajax.php' },
        { userAgent: '*', type: 'disallow', path: '/readme.html' },
      ]);
    } else if (preset === 'ecommerce') {
      setRules([
        { userAgent: '*', type: 'disallow', path: '/cart/' },
        { userAgent: '*', type: 'disallow', path: '/checkout/' },
        { userAgent: '*', type: 'disallow', path: '/account/' },
        { userAgent: '*', type: 'disallow', path: '/*?*sort=' },
      ]);
    } else if (preset === 'ai-block') {
      setRules([
        { userAgent: 'GPTBot', type: 'disallow', path: '/' },
        { userAgent: 'ChatGPT-User', type: 'disallow', path: '/' },
        { userAgent: 'CCBot', type: 'disallow', path: '/' },
        { userAgent: 'AnthropicAI', type: 'disallow', path: '/' },
        { userAgent: 'ClaudeBot', type: 'disallow', path: '/' },
      ]);
    }
  };

  const robotsTxtContent = useMemo(() => {
    const grouped: Record<string, typeof rules> = {};
    rules.forEach((r) => {
      const agent = r.userAgent.trim() || '*';
      if (!grouped[agent]) grouped[agent] = [];
      grouped[agent].push(r);
    });

    let output = '# Generated by WebTools SEO Suite\n\n';
    Object.entries(grouped).forEach(([agent, agentRules]) => {
      output += `User-agent: ${agent}\n`;
      agentRules.forEach((rule) => {
        if (rule.path) {
          const capitalized = rule.type === 'disallow' ? 'Disallow' : 'Allow';
          output += `${capitalized}: ${rule.path}\n`;
        }
      });
      if (crawlDelay) {
        output += `Crawl-delay: ${crawlDelay}\n`;
      }
      output += '\n';
    });

    if (sitemapUrl) {
      output += `Sitemap: ${sitemapUrl.trim()}\n`;
    }

    return output.trim();
  }, [rules, crawlDelay, sitemapUrl]);

  // Test URL resolution
  const testResult = useMemo(() => {
    if (!testUrl) return null;
    // Check specific agent first, then wildcard *
    const matchingRules = rules.filter(
      (r) => r.userAgent === testBot || r.userAgent === '*'
    );

    let isDisallowed = false;
    let matchedRule = null;

    for (const r of matchingRules) {
      if (!r.path) continue;
      // Simple prefix / wildcard check
      const pattern = r.path.replace(/\*/g, '.*');
      const regex = new RegExp('^' + pattern);
      if (regex.test(testUrl) || testUrl.startsWith(r.path)) {
        if (r.type === 'disallow') {
          isDisallowed = true;
          matchedRule = r;
        } else {
          isDisallowed = false;
          matchedRule = r;
        }
      }
    }

    return {
      allowed: !isDisallowed,
      rule: matchedRule,
    };
  }, [testUrl, testBot, rules]);

  return (
    <div className="space-y-6">
      {/* Header & Preset Buttons */}
      <div className="flex flex-wrap items-center justify-between gap-3 bg-secondary/40 p-4 rounded-xl border border-border">
        <div>
          <h3 className="text-sm font-semibold text-foreground">Quick Presets</h3>
          <p className="text-xs text-muted-foreground">Apply optimized rule templates for popular platforms</p>
        </div>
        <div className="flex flex-wrap gap-2">
          <button
            onClick={() => applyPreset('wordpress')}
            className="px-3 py-1.5 text-xs font-medium rounded-lg bg-background border border-border text-foreground hover:bg-secondary/60 transition"
          >
            WordPress
          </button>
          <button
            onClick={() => applyPreset('ecommerce')}
            className="px-3 py-1.5 text-xs font-medium rounded-lg bg-background border border-border text-foreground hover:bg-secondary/60 transition"
          >
            E-Commerce
          </button>
          <button
            onClick={() => applyPreset('ai-block')}
            className="px-3 py-1.5 text-xs font-medium rounded-lg bg-background border border-border text-foreground hover:bg-secondary/60 transition"
          >
            Block AI Scrapers
          </button>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left: Configuration Form */}
        <div className="lg:col-span-7 space-y-5">
          <div className="bg-card border border-border rounded-xl p-5 space-y-4 shadow-xs">
            <h4 className="font-semibold text-foreground text-sm flex items-center gap-2">
              <Settings className="w-4 h-4 text-indigo-600" /> General Directives
            </h4>
            <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
              <div className="md:col-span-2">
                <label className="block text-xs font-medium text-foreground mb-1">Sitemap URL</label>
                <input
                  type="url"
                  value={sitemapUrl}
                  onChange={(e) => setSitemapUrl(e.target.value)}
                  placeholder="https://example.com/sitemap.xml"
                  className="w-full px-3 py-2 text-xs border border-border rounded-lg focus:ring-2 focus:ring-indigo-500 focus:outline-hidden"
                />
              </div>
              <div>
                <label className="block text-xs font-medium text-foreground mb-1">Crawl Delay (s)</label>
                <input
                  type="number"
                  value={crawlDelay}
                  onChange={(e) => setCrawlDelay(e.target.value)}
                  placeholder="e.g., 5"
                  className="w-full px-3 py-2 text-xs border border-border rounded-lg focus:ring-2 focus:ring-indigo-500 focus:outline-hidden"
                />
              </div>
            </div>
          </div>

          {/* Rules Builder */}
          <div className="bg-card border border-border rounded-xl p-5 space-y-4 shadow-xs">
            <div className="flex items-center justify-between">
              <h4 className="font-semibold text-foreground text-sm flex items-center gap-2">
                <List className="w-4 h-4 text-indigo-600" /> Crawl Directives ({rules.length})
              </h4>
              <button
                onClick={addRule}
                className="px-3 py-1.5 text-xs font-medium bg-indigo-50 text-indigo-600 hover:bg-indigo-100 rounded-lg flex items-center gap-1 transition"
              >
                <Plus className="w-3.5 h-3.5" /> Add Rule
              </button>
            </div>

            <div className="space-y-3 max-h-[380px] overflow-y-auto pr-1">
              {rules.map((rule, idx) => (
                <div key={idx} className="flex flex-wrap md:flex-nowrap items-center gap-2 p-3 bg-secondary/40 border border-border rounded-lg">
                  <select
                    value={rule.userAgent}
                    onChange={(e) => updateRule(idx, 'userAgent', e.target.value)}
                    className="text-xs px-2.5 py-1.5 bg-background border border-border rounded-lg font-medium text-foreground focus:outline-hidden"
                  >
                    <option value="*">* (All Bots)</option>
                    <option value="Googlebot">Googlebot</option>
                    <option value="Bingbot">Bingbot</option>
                    <option value="GPTBot">GPTBot (OpenAI)</option>
                    <option value="ClaudeBot">ClaudeBot</option>
                    <option value="CCBot">CCBot</option>
                    <option value="Baiduspider">Baiduspider</option>
                    <option value="Yandex">Yandex</option>
                  </select>

                  <select
                    value={rule.type}
                    onChange={(e) => updateRule(idx, 'type', e.target.value)}
                    className={`text-xs px-2 py-1.5 font-semibold rounded-lg border focus:outline-hidden ${
                      rule.type === 'disallow'
                        ? 'bg-rose-50 text-rose-700 border-rose-200'
                        : 'bg-emerald-50 text-emerald-700 border-emerald-200'
                    }`}
                  >
                    <option value="disallow">Disallow</option>
                    <option value="allow">Allow</option>
                  </select>

                  <input
                    type="text"
                    value={rule.path}
                    onChange={(e) => updateRule(idx, 'path', e.target.value)}
                    placeholder="/path/to/block/"
                    className="flex-1 text-xs px-3 py-1.5 bg-background border border-border rounded-lg focus:outline-hidden font-mono text-foreground"
                  />

                  <button
                    onClick={() => removeRule(idx)}
                    className="p-1.5 text-muted-foreground hover:text-rose-600 rounded-lg hover:bg-rose-50 transition"
                    title="Remove rule"
                  >
                    <Trash2 className="w-4 h-4" />
                  </button>
                </div>
              ))}
            </div>
          </div>

          {/* Rule Testing Simulator */}
          <div className="bg-indigo-50/60 border border-indigo-100 rounded-xl p-4 space-y-3">
            <h5 className="text-xs font-bold text-indigo-950 uppercase tracking-wider flex items-center gap-1.5">
              <Zap className="w-3.5 h-3.5 text-indigo-600" /> Live URL Rule Tester
            </h5>
            <div className="grid grid-cols-1 sm:grid-cols-12 gap-2">
              <select
                value={testBot}
                onChange={(e) => setTestBot(e.target.value)}
                className="sm:col-span-4 text-xs px-2.5 py-1.5 bg-white border border-indigo-200 rounded-lg text-foreground"
              >
                <option value="*">* (All Bots)</option>
                <option value="Googlebot">Googlebot</option>
                <option value="GPTBot">GPTBot</option>
              </select>
              <input
                type="text"
                value={testUrl}
                onChange={(e) => setTestUrl(e.target.value)}
                placeholder="/admin/login"
                className="sm:col-span-8 text-xs px-3 py-1.5 bg-white border border-indigo-200 rounded-lg font-mono"
              />
            </div>
            {testResult && (
              <div
                className={`p-2.5 rounded-lg text-xs font-medium flex items-center justify-between ${
                  testResult.allowed
                    ? 'bg-emerald-100/80 text-emerald-900 border border-emerald-200'
                    : 'bg-rose-100/80 text-rose-900 border border-rose-200'
                }`}
              >
                <span className="flex items-center gap-1.5">
                  {testResult.allowed ? (
                    <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                  ) : (
                    <XCircle className="w-4 h-4 text-rose-600" />
                  )}
                  {testResult.allowed
                    ? `ALLOWED: Crawlers can index "${testUrl}"`
                    : `BLOCKED: Crawlers are prohibited from accessing "${testUrl}"`}
                </span>
                {testResult.rule && (
                  <span className="font-mono text-[10px] bg-white/70 px-2 py-0.5 rounded">
                    Rule: {testResult.rule.type} {testResult.rule.path}
                  </span>
                )}
              </div>
            )}
          </div>
        </div>

        {/* Right: Code Output */}
        <div className="lg:col-span-5 flex flex-col space-y-3">
          <div className="flex items-center justify-between">
            <h4 className="font-semibold text-foreground text-sm flex items-center gap-2">
              <FileCode className="w-4 h-4 text-indigo-600" /> Generated robots.txt
            </h4>
            <div className="flex items-center gap-2">
              <button
                onClick={() => copyToClipboard(robotsTxtContent, setCopied)}
                className="px-2.5 py-1 text-xs font-medium rounded-lg bg-indigo-600 text-white hover:bg-indigo-700 flex items-center gap-1 transition shadow-xs"
              >
                {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                {copied ? 'Copied' : 'Copy'}
              </button>
              <button
                onClick={() => downloadFile('robots.txt', robotsTxtContent)}
                className="px-2.5 py-1 text-xs font-medium rounded-lg bg-secondary/60 text-foreground hover:bg-secondary flex items-center gap-1 transition"
              >
                <Download className="w-3.5 h-3.5" /> Download
              </button>
            </div>
          </div>

          <pre className="flex-1 bg-slate-900 text-slate-100 p-4 rounded-xl text-xs font-mono overflow-x-auto border border-slate-800 min-h-[380px] leading-relaxed">
            {robotsTxtContent}
          </pre>
        </div>
      </div>
    </div>
  );
};

